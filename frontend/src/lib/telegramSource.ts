/**
 * Источники, автоматически собранные из Telegram-каналов (сейчас —
 * единственный, "Remote Frontend Jobs (TG)"), выделяются на карточке
 * синей обводкой + иконкой Telegram, чтобы было явно видно, что вакансия
 * не с обычного джоб-борда. Определяем по суффиксу "(TG)" в имени
 * источника, а не хардкодом одного конкретного имени — следующий
 * TG-источник (если появится) подхватится автоматически.
 */
export function isTelegramSource(sourceName: string): boolean {
  return sourceName.endsWith("(TG)");
}
